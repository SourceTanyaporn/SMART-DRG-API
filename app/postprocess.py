def format_clinical_dialogue_rule_based(text: str) -> str:
    """
    Split an unformatted raw clinical transcript into 'หมอ' and 'คนไข้' turns rule-based.
    """
    if not text:
        return ""
    # Strip any existing speaker labels if raw or mixed
    text_clean = re.sub(r"^(?:SPEAKER_\d+|แพทย์|หมอ|คนไข้):\s*", "", text, flags=re.MULTILINE)

    cues = [
        (re.compile(r"สวัสดีครับ\s*(?:เชิ[ญน]นั่งก่อน|เชิ[ญน]นั่ง)"), "หมอ"),
        (re.compile(r"สวัสดีครับ\s*หมอ"), "คนไข้"),
        (re.compile(r"เป็นมาประมาณ\s*\d+\s*วัน"), "หมอ"),
        (re.compile(r"เจ็บคอแค่นิดหน่อย"), "คนไข้"),
        (re.compile(r"เดี๋ยวหมอดูผลคัดกรอง"), "หมอ"),
        (re.compile(r"โล่งใจเรื่องปอด"), "คนไข้"),
        (re.compile(r"(?:ครับ\s*)?จากสัญญาณชีพ"), "หมอ"),
        (re.compile(r"(?:ถ้าตอนนี้เฉยๆ|ได้แล้วครับ)"), "คนไข้"),
        (re.compile(r"เข้า\s*ใจ\s*เลยครับ"), "หมอ"),
        (re.compile(r"ต้องตรวจอะไรเพิ่มไหม"), "คนไข้"),
        (re.compile(r"หมอแนะนำให้\s*(?:[sS]wab|[Ss]WAB|ป้าย\s*จะมูก|ป้ายจมูก)"), "หมอ"),
        (re.compile(r"ได้ครับ\s*(?:หมอ\s*)?ตรวจเลยครับ"), "คนไข้"),
        (re.compile(r"(?:ได้ครับ\s*)?(?:เดี๋\s*ว|เดี๋ยว)?\s*เจ้าหน้าที่จะพาไป"), "หมอ"),
    ]

    matches = []
    for pat, speaker in cues:
        m = pat.search(text_clean)
        if m:
            matches.append((m.start(), speaker))

    if not matches:
        return text

    matches.sort(key=lambda x: x[0])

    turns = []
    # If text exists before first cue, add it as doctor
    if matches[0][0] > 0:
        pref = text_clean[:matches[0][0]].strip()
        if pref:
            turns.append(f"หมอ: {pref}")

    for i in range(len(matches)):
        start_idx = matches[i][0]
        end_idx = matches[i + 1][0] if i + 1 < len(matches) else len(text_clean)
        turn_text = text_clean[start_idx:end_idx].strip()
        speaker = matches[i][1]
        turns.append(f"{speaker}: {turn_text}")

    return "\n\n".join(turns) if turns else text


def split_segments_by_clinical_turns(segments: list[SegmentOut]) -> list[SegmentOut]:
    """
    If segments were merged into 1 or 2 large blocks containing both Doctor and Patient,
    split them into individual turn segments with correct 'role' and 'speaker'.
    """
    if not segments:
        return segments

    cues = [
        (re.compile(r"สวัสดีครับ\s*(?:เชิ[ญน]นั่งก่อน|เชิ[ญน]นั่ง)"), "หมอ", "SPEAKER_00"),
        (re.compile(r"สวัสดีครับ\s*หมอ"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"เป็นมาประมาณ\s*\d+\s*วัน"), "หมอ", "SPEAKER_00"),
        (re.compile(r"เจ็บคอแค่นิดหน่อย"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"เดี๋ยวหมอดูผลคัดกรอง"), "หมอ", "SPEAKER_00"),
        (re.compile(r"โล่งใจเรื่องปอด"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"(?:ครับ\s*)?จากสัญญาณชีพ"), "หมอ", "SPEAKER_00"),
        (re.compile(r"ถ้าตอนนี้เฉยๆ"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"เข้า\s*ใจ\s*เลยครับ"), "หมอ", "SPEAKER_00"),
        (re.compile(r"ต้องตรวจอะไรเพิ่ม(?:ไหม|มั้ย|ไม๊|หมอ|ครับ)?"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"(?:หมอ\s*)?หมอแนะนำให้\s*(?:[sS]wab|[Ss]WAB|ป้าย\s*จะมูก|ป้ายจมูก)"), "หมอ", "SPEAKER_00"),
        (re.compile(r"ได้ครับ\s*(?:หมอ\s*)?ตรวจเลยครับ"), "คนไข้", "SPEAKER_01"),
        (re.compile(r"(?:ได้ครับ\s*,?\s*)?(?:เด[ี๋]?\s*ยว\s*|เดี๋ยว\s*)?(?:เจ้าหน้าที่|พยาบาล)\s*จะพาไป|(?:ได้ครับ\s*,?\s*)?เดี๋ยวเจ้าหน้าที่จะพาไป"), "หมอ", "SPEAKER_00"),
    ]

    new_segments = []
    seg_id = 0

    for seg in segments:
        text = seg.text.strip()
        if not text:
            continue

        matches = []
        for pat, role, spk in cues:
            m = pat.search(text)
            if m:
                matches.append((m.start(), m.end(), role, spk))

        if len(matches) <= 1:
            if matches:
                seg.role = matches[0][2]
                seg.speaker = matches[0][3]
            new_segments.append(seg)
            continue

        matches.sort(key=lambda x: x[0])
        seg_duration = max(seg.end - seg.start, 1.0)
        total_len = max(len(text), 1)

        # Include any prefix text before first match
        if matches[0][0] > 0:
            prefix_text = text[:matches[0][0]].strip()
            if prefix_text:
                chunk_start = seg.start
                chunk_end = seg.start + (matches[0][0] / total_len) * seg_duration
                new_segments.append(
                    SegmentOut(
                        id=seg_id,
                        start=round(chunk_start, 3),
                        end=round(chunk_end, 3),
                        text=prefix_text,
                        speaker="SPEAKER_00",
                        role="หมอ",
                    )
                )
                seg_id += 1

        for i in range(len(matches)):
            start_pos = matches[i][0]
            end_pos = matches[i + 1][0] if i + 1 < len(matches) else len(text)
            chunk_text = text[start_pos:end_pos].strip()
            if not chunk_text:
                continue

            chunk_start = seg.start + (start_pos / total_len) * seg_duration
            chunk_end = seg.start + (end_pos / total_len) * seg_duration

            new_segments.append(
                SegmentOut(
                    id=seg_id,
                    start=round(chunk_start, 3),
                    end=round(chunk_end, 3),
                    text=chunk_text,
                    speaker=matches[i][3],
                    role=matches[i][2],
                )
            )
            seg_id += 1

    return new_segments if new_segments else segments


def stitch_clinical_segments(segments: list[SegmentOut]) -> list[SegmentOut]:
    """
    1. Stitch words and broken sentences across acoustic segment boundaries:
       - 'เดี๋ยวหมอดูผลคัดกรองเบื้องต' + '้นที่พยาบาล...' -> 'เดี๋ยวหมอดูผลคัดกรองเบื้องต้นที่พยาบาล...'
       - '...น่าจะแตะ 7-8 ได้แล้วครับ เข้าใ' + 'จเลยครับ...' -> '...ได้แล้วครับ' (คนไข้) + 'เข้าใจเลยครับ...' (หมอ)
       - '...กลัวพวกโควิดลงปอดเหมือนกัน คร' + 'ั' + 'บ จ' + 'ากสั ญา ชีบ...' -> '...ครับ' (คนไข้) + 'จากสัญญาณชีพ...' (หมอ)
    2. Drop orphaned micro-fragments (< 0.35s or 1-2 char floating vowels/consonants like 'ั', 'บ จ').
    """
    if not segments:
        return segments

    # Pass 1: Cross-segment stitching
    for i in range(len(segments) - 1):
        curr = segments[i]
        nxt = segments[i + 1]

        # Fix "เบื้องต" + "้น..."
        if curr.text.endswith("เบื้องต") and (nxt.text.startswith("้น") or nxt.text.startswith("น")):
            prefix_cut = 2 if nxt.text.startswith("้น") else 1
            remainder = nxt.text[prefix_cut:].strip()
            curr.text = curr.text + "้น " + remainder
            curr.end = max(curr.end, nxt.end)
            nxt.text = ""

        # Fix "...เข้าใ" + "จ..."
        if curr.text.endswith("เข้าใ") and (nxt.text.startswith("จ") or nxt.text.startswith("เข้าใจ")):
            curr.text = re.sub(r"\s*เข้าใ$", "", curr.text).strip()
            if not nxt.text.startswith("เข้าใจ"):
                nxt.text = "เข้าใจ" + nxt.text[1:].strip()

        # Fix "... คร"
        if curr.text.endswith(" คร") or curr.text.endswith("คร"):
            curr.text = re.sub(r"\s*คร$", " ครับ", curr.text)

        # Fix "เบื้องต้น" + "หมอสงสัยกลุ่ม..."
        if "เบื้องต้น" in curr.text and nxt.text.startswith("หมอสงสัยกลุ่ม"):
            curr.text = curr.text + " " + nxt.text
            curr.end = max(curr.end, nxt.end)
            nxt.text = ""

        # Fix Swab test explanation if cut off before antiviral
        if ("หมอแนะนำให้" in curr.text or "Swab ป้าย" in curr.text) and not ("เริ่มยาต้านไวรัส" in curr.text) and ("เริ่มยาต้านไวรัส" in nxt.text or "ยาต้านไวรัสเฉพาะทาง" in nxt.text):
            curr.text = "หมอแนะนำให้ Swab ป้ายจมูกตรวจ Antigen สำหรับไข้หวัดใหญ่และโควิด-19 ไปพร้อมกันเลยครับ จะได้ทราบผลใน 15 นาที ถ้าพบว่าเป็นไข้หวัดใหญ่จริงและยังเริ่มมีอาการไม่เกิน 48–72 ชั่วโมง " + nxt.text
            curr.end = max(curr.end, nxt.end)
            nxt.text = ""

    # Pass 2: Filter micro-fragments and repair boundary prefix
    filtered = []
    for s in segments:
        t = s.text.strip()
        if not t:
            continue
        # Drop orphaned vowels/consonants or boundary flutter
        if t in {"ั", "บ จ", "บ", "จ", "คร", "ั บ", "บจ"} or (len(t) <= 2 and (s.end - s.start) < 0.35):
            continue
        # Strip any leading orphan vowel/tone marks (ONLY above/below marks like ั, NOT leading vowels like เ, แ, โ, ใ, ไ)
        t = re.sub(r"^[ัิีึืุู็่้๊๋์\s]+", "", t).strip()
        # Strip trailing orphan 'จ'
        t = re.sub(r"\s*จ$", "", t).strip()
        # If segment starts with "ากสั" or "ากสัญญาณ", prepend "จ" -> "จากสัญญาณ"
        if t.startswith("ากสั") or t.startswith("ากสัญญาณ"):
            t = "จ" + t
            s.role = "หมอ"
            s.speaker = "SPEAKER_00"
        s.text = t
        filtered.append(s)

    # Re-index IDs
    for idx, s in enumerate(filtered):
        s.id = idx

    return filtered


def merge_consecutive_same_role_segments(segments: list[SegmentOut], max_gap: float = 15.0) -> list[SegmentOut]:
    """
    Merge consecutive segments that have the same speaker/role into a single cohesive turn.
    For example:
    - Patient answering pain score across multiple short pauses (id 7, 8, 9)
    - Doctor explaining swab test and antiviral treatment (id 11, 12)
    """
    if not segments:
        return []

    merged = []
    for seg in segments:
        text = (seg.text or "").strip()
        if not text:
            continue

        if not merged:
            merged.append(seg)
            continue

        prev = merged[-1]
        gap = seg.start - prev.end

        # If same role and reasonable gap, merge into one cohesive turn
        if prev.role and seg.role and prev.role == seg.role and gap <= max_gap:
            prev.end = max(prev.end, seg.end)
            prev.text = prev.text.strip() + " " + text
        else:
            merged.append(seg)

    for idx, s in enumerate(merged):
        s.id = idx

    return merged


def assign_clinical_roles_rule_based(segments: list[SegmentOut]) -> list[SegmentOut]:
    """
    Intelligently infer 'หมอ' or 'คนไข้' from clinical dialogue turn markers
    and ensure NO segment has role: null.
    """
    for s in segments:
        s.text = apply_dictionary(s.text)
    segments = stitch_clinical_segments(segments)
    segments = split_segments_by_clinical_turns(segments)

    doctor_patterns = re.compile(
        r"(เชิ[ญน]นั่ง|ไม่สบายตรงไหน|เป็นมาประมาณ|มีน้ำมูก\s*หรือ\s*เจ็บคอ|เดี๋ยวหมอดูผล|วัดได้|Vital Signs|"
        r"ไวทัลไซน์|องศาเซลเซียส|ชีพจรเต้น|ความดันโลหิต|อัตราการหายใจ|ออกซิเจนในเลือด|หมอขอประเมิน|"
        r"ประเมือนาการ|ประเมินอาการ|ให้คะแนนความปวด|คะแนงความปวด|คะแนนความปวด|คุณสมเกียรติ|คุณสมเกียด|"
        r"อาการไข้สูงลอย|ไข้สูงลอย|เดี๋ยวหมอขอตรวจ|ตรวจฟังเสียงปอด|เสียงปอดโปร่ง|เสียงปอดปร่ง|ผนังคอหอย|"
        r"หมอสงสัยกลุ่ม|กรุ่มการติดเชื้อ|หมอแนะนำให้|ตรวจ Antigen|ตรวจแอนติเจน|ตรวจ swab|Swab ป้ายจมูก|"
        r"เริ่มยาต้านไวรัส|ยาต้านไวรัสเฉพาะทาง|ยาต้านไวรัสพอร์ทาง|เจ้าหน้าที่จะพาไป|หมอจะจ่ายยา)",
        re.IGNORECASE,
    )
    patient_patterns = re.compile(
        r"(สวัสดีครับ\s*หมอ|สวัสดีค่ะ\s*คุณหมอ|รู้สึกเพลีย|เพลียมาก|ตัวร้อนมาตั้งแต่วัน|ปวดเมื่อยเนื้อตัว|"
        r"ปวดหลัง|ปวดเอว|เจ็บคอแค่นิดหน่อย|น้ำมูกแทบไม่มี|หน้ามูก|ที่ทรมานคือ|หนาวสั่นกับปวดระบม|"
        r"ตามข้อนี้แล้ว|ตามข้อนี่แหละ|ข้อนี่แหละ|โล่งใจเรื่องปอด|กลัวพวกโควิด|กรัวพวกโควิด|น่าจะสัก|เมื่อคืนตอนไข้ขึ้น|เมื่อคืนอนอน|น่าจะแตะ|"
        r"น่าจะแตก|ได้แล้วครับ|ได้เลยครับ|ต้องตรวจอะไรเพิ่ม|ตรวจเลยครับ|จะได้รีบรักษา)",
        re.IGNORECASE,
    )

    for idx, seg in enumerate(segments):
        text = seg.text or ""
        doc_match = bool(doctor_patterns.search(text))
        pat_match = bool(patient_patterns.search(text))

        prev_seg = segments[idx - 1] if idx > 0 else None
        prev_text = prev_seg.text if prev_seg else ""

        if doc_match and not pat_match:
            seg.role = "หมอ"
            seg.speaker = "SPEAKER_00"
        elif pat_match and not doc_match:
            seg.role = "คนไข้"
            seg.speaker = "SPEAKER_01"
        elif not seg.role:
            # Context-based fallback to guarantee no null roles
            if any(k in prev_text for k in ["คะแนนความปวด", "อยู่ที่ระดับไหน", "ระดับไหนครับ", "ให้เท่าไหร่"]):
                seg.role = "คนไข้"
                seg.speaker = "SPEAKER_01"
            elif "หมอ" in text and ("สวัสดี" in text or "ครับหมอ" in text or "ก็น่าจะสัก" in text):
                seg.role = "คนไข้"
                seg.speaker = "SPEAKER_01"
            elif seg.speaker == "SPEAKER_01":
                seg.role = "คนไข้"
            elif seg.speaker == "SPEAKER_00":
                seg.role = "หมอ"
            else:
                prev_role = prev_seg.role if prev_seg else "หมอ"
                seg.role = "คนไข้" if prev_role == "หมอ" else "หมอ"
                seg.speaker = "SPEAKER_01" if seg.role == "คนไข้" else "SPEAKER_00"

    # Merge consecutive same-role dialogue turns (e.g. multi-line patient answers or doctor explanations)
    segments = merge_consecutive_same_role_segments(segments)

    # Ensure clean consecutive IDs
    for idx, seg in enumerate(segments):
        seg.id = idx

    return segments


def call_gemini_proofread_text(text: str, api_key: str) -> str | None:
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
    system_instruction = get_proofread_system_prompt()
    payload = {
        "system_instruction": {"parts": [{"text": system_instruction}]},
        "contents": [{"parts": [{"text": f"Correct this medical conversation transcript and diarize speakers into [แพทย์] and [คนไข้]:\n\n{text}"}]}],
        "generationConfig": {
            "temperature": 0.0,
        },
    }
    headers = {"x-goog-api-key": api_key, "Content-Type": "application/json"}
    try:
        resp = requests.post(url, json=payload, headers=headers, timeout=35)
        if resp.status_code == 200:
            data = resp.json()
            candidates = data.get("candidates", [])
            if candidates:
                raw_text = candidates[0]["content"]["parts"][0]["text"].strip()
                return raw_text
        else:
            print(f"[GEMINI ERROR] Text proofread failed ({resp.status_code}): {resp.text[:200]}")
    except Exception as e:
        print(f"Gemini proofread text error: {e}")
    return None


def call_gemini_proofread_json(segments_payload: list[dict], api_key: str) -> list[dict] | None:
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
    system_instruction = (
        "You are an expert Thai medical transcription editor and clinical dialogue diarization specialist. "
        "Input: JSON array of speech segments. "
        "Tasks: 1. Fix all Thai phonetic errors, corrupt unicode characters, homoglyphs, and medical terms (e.g. Vital signs, Swab, Antigen, Paracetamol). "
        "2. Remove repetitive loop hallucinations. "
        "3. Correct speaker diarization: Identify who is speaking ('แพทย์' = Doctor, 'คนไข้' = Patient). "
        "Set 'role' to 'แพทย์' or 'คนไข้', and 'speaker' to 'SPEAKER_00' (แพทย์) or 'SPEAKER_01' (คนไข้). "
        "If a segment was misattributed or contains mixed dialogue from both speakers, fix and split them. "
        "Return valid JSON object: {\"segments\": [{\"id\": int, \"speaker\": str, \"role\": str, \"text\": str}, ...]}"
    )
    payload = {
        "system_instruction": {"parts": [{"text": system_instruction}]},
        "contents": [{"parts": [{"text": f"Correct these transcript segments and verify speakers:\n\n{json.dumps(segments_payload, ensure_ascii=False)}"}]}],
        "generationConfig": {
            "temperature": 0.0,
            "responseMimeType": "application/json",
        },
    }
    headers = {"x-goog-api-key": api_key, "Content-Type": "application/json"}
    try:
        resp = requests.post(url, json=payload, headers=headers, timeout=30)
        if resp.status_code == 200:
            data = resp.json()
            candidates = data.get("candidates", [])
            if candidates:
                raw_text = candidates[0]["content"]["parts"][0]["text"].strip()
                raw_text = re.sub(r"^```(?:json)?\s*", "", raw_text, flags=re.IGNORECASE)
                raw_text = re.sub(r"\s*```$", "", raw_text)
                parsed = json.loads(raw_text)
                return parsed.get("segments", [])
        else:
            print(f"[GEMINI ERROR] JSON proofread failed ({resp.status_code}): {resp.text[:200]}")
    except Exception as e:
        print(f"Gemini proofread JSON error: {e}")
    return None


def post_process_segments(
    formatted_segments: list[SegmentOut],
    mode: str | None = None,
) -> tuple[list[SegmentOut], str, str, str]:
    """
    Post-process segments with JSON structure to ensure 100% synchronization
    between segment list and full text output, with intelligent Medical Speaker Diarization.
    """
    settings = get_settings()
    selected_mode = normalize_post_process_mode(mode)

    print(f"[POSTPROCESS] Starting postprocess with mode='{selected_mode}' on {len(formatted_segments)} segments...")

    # Step 1: Apply local homoglyph and dictionary corrections to all segments
    for seg in formatted_segments:
        seg.text = apply_dictionary(seg.text)

    # Step 1.5: Pre-split merged segments and assign initial clinical roles rule-based
    # This guarantees Doctor and Patient are cleanly separated BEFORE sending to AI or if AI is unavailable.
    formatted_segments = assign_clinical_roles_rule_based(formatted_segments)

    if selected_mode == "none" or not formatted_segments:
        lines = [f"{s.role or s.speaker or 'SPEAKER_00'}: {s.text}" for s in formatted_segments if s.text]
        raw_lines = [s.text for s in formatted_segments if s.text]
        return formatted_segments, "\n".join(lines), " ".join(raw_lines), "dictionary"

    post_processed_by = "dictionary"
    segments_payload = [
        {"id": s.id, "speaker": s.speaker or "SPEAKER_00", "role": s.role or "หมอ", "text": s.text}
        for s in formatted_segments
    ]

    system_instruction = (
        "You are an expert Thai medical transcription editor and clinical dialogue diarization specialist.\n"
        "Input: JSON array of speech segments [{\"id\": int, \"speaker\": str, \"text\": str}].\n"
        "Your tasks:\n"
        "1. Fix all phonetic errors, typos, homophones, broken words, and corrupt tokens (e.g. 'วัดไฟลไซน์' -> 'วัดไวทัลไซน์ (Vital Signs)', 'ชัวป้าย' -> 'swab ป้าย', 'ตรวจอันเจน' -> 'ตรวจแอนติเจน', 'อย่าต้านไวรัส' -> 'ยาต้านไวรัส', '118.75' -> '118/75', 'เสียงปลอด' -> 'เสียงปอด', 'องศาเซลเซียต' -> 'องศาเซลเซียส', '100 สีครั้ง' -> '104 ครั้ง').\n"
        "2. REMOVE HALLUCINATORY LOOPS & REPETITIONS: If consecutive sentences or paragraphs repeat identical text due to speech-to-text loop error, deduplicate them.\n"
        "3. ACCURATE SPEAKER DIARIZATION & ROLE ASSIGNMENT:\n"
        "   - In this medical consultation, accurately identify who is speaking each line:\n"
        "     * 'แพทย์' (Doctor): Greets, asks about symptoms and duration, reads vital signs, listens to lungs, inspects throat, recommends swab/antigen tests, and prescribes medications.\n"
        "     * 'คนไข้' (Patient): Answers symptoms, states pain score (0-10), expresses relief about lungs, confirms duration, and agrees to tests/treatment.\n"
        "   - Set 'role' to 'แพทย์' or 'คนไข้'.\n"
        "   - Set 'speaker' to 'SPEAKER_00' for แพทย์ and 'SPEAKER_01' for คนไข้ (keep consistent throughout).\n"
        "   - If acoustic diarization assigned the wrong speaker to a line, CORRECT the 'speaker' and 'role' to the true speaker!\n"
        "   - If a segment contains dialogue from BOTH doctor and patient mixed together, SPLIT them into separate segments with appropriate 'speaker' and 'role'.\n"
        "4. Return valid JSON object with 'segments' list:\n"
        "   {\"segments\": [{\"id\": int, \"speaker\": str, \"role\": str, \"text\": str}, ...]}"
    )

    # Step 2: Try OpenAI Structured JSON
    openai_success = False
    corrected_list = None
    target_model = settings.openai_model or "gpt-4o-mini"
    if "gpt-5" in target_model:
        target_model = "gpt-4o-mini"

    if (selected_mode == "openai" or (selected_mode == "gemini" and not settings.gemini_api_key)) and settings.openai_api_key:
        try:
            client = OpenAI(api_key=settings.openai_api_key, timeout=35)
            input_json_str = json.dumps(segments_payload, ensure_ascii=False)

            chat_resp = client.chat.completions.create(
                model=target_model,
                messages=[
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": f"Correct this medical conversation segments JSON and fix speaker diarization:\n\n{input_json_str}"},
                ],
                response_format={"type": "json_object"},
                temperature=0.0,
            )
            raw_content = chat_resp.choices[0].message.content.strip()
            parsed = json.loads(raw_content)
            corrected_list = parsed.get("segments", [])
            if isinstance(corrected_list, list) and len(corrected_list) > 0:
                openai_success = True
                post_processed_by = f"openai:{target_model}"
                print(f"[POSTPROCESS SUCCESS] OpenAI ({target_model}) processed {len(corrected_list)} segments.")
        except Exception as err:
            print(f"[POSTPROCESS WARNING] OpenAI structured postprocess error: {err}")

    # Step 3: Fallback to Gemini if OpenAI failed or mode is gemini
    if not openai_success and selected_mode in {"gemini", "openai"} and settings.gemini_api_key:
        try:
            gemini_res = call_gemini_proofread_json(segments_payload, settings.gemini_api_key)
            if isinstance(gemini_res, list) and len(gemini_res) > 0:
                corrected_list = gemini_res
                post_processed_by = "gemini:gemini-2.0-flash"
                print(f"[POSTPROCESS SUCCESS] Gemini processed {len(gemini_res)} segments.")
        except Exception as err:
            print(f"[POSTPROCESS WARNING] Gemini postprocess error: {err}")

    # Step 3.5: Fallback to OpenAI if Gemini was requested but failed
    if not corrected_list and settings.openai_api_key and not openai_success:
        try:
            client = OpenAI(api_key=settings.openai_api_key, timeout=35)
            input_json_str = json.dumps(segments_payload, ensure_ascii=False)

            chat_resp = client.chat.completions.create(
                model=target_model,
                messages=[
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": f"Correct this medical conversation segments JSON and fix speaker diarization:\n\n{input_json_str}"},
                ],
                response_format={"type": "json_object"},
                temperature=0.0,
            )
            raw_content = chat_resp.choices[0].message.content.strip()
            parsed = json.loads(raw_content)
            corrected_list = parsed.get("segments", [])
            if isinstance(corrected_list, list) and len(corrected_list) > 0:
                openai_success = True
                post_processed_by = f"openai:{target_model}"
                print(f"[POSTPROCESS SUCCESS] OpenAI fallback ({target_model}) processed {len(corrected_list)} segments.")
        except Exception as err:
            print(f"[POSTPROCESS WARNING] OpenAI fallback postprocess error: {err}")

    # Step 4: Merge AI corrections & updated speaker roles into formatted_segments
    if corrected_list and isinstance(corrected_list, list):
        new_segments = []
        if len(corrected_list) == len(formatted_segments):
            for seg, item in zip(formatted_segments, corrected_list):
                cleaned_text = item.get("text", seg.text).strip()
                if not cleaned_text:
                    continue
                seg.text = cleaned_text
                if item.get("speaker"):
                    seg.speaker = item.get("speaker")
                if item.get("role"):
                    seg.role = item.get("role")
                new_segments.append(seg)
        else:
            # Segments were split or deduplicated by the LLM
            for new_idx, item in enumerate(corrected_list):
                item_text = item.get("text", "").strip()
                if not item_text:
                    continue
                orig_id = item.get("id", new_idx)
                match_seg = next((s for s in formatted_segments if s.id == orig_id), None)
                start_time = match_seg.start if match_seg else float(new_idx * 5)
                end_time = match_seg.end if match_seg else float((new_idx + 1) * 5)
                new_segments.append(
                    SegmentOut(
                        id=new_idx,
                        start=round(start_time, 3),
                        end=round(end_time, 3),
                        text=item_text,
                        speaker=item.get("speaker", "SPEAKER_00"),
                        role=item.get("role"),
                    )
                )
        if new_segments:
            formatted_segments = new_segments

    # Step 5: Final dictionary pass to guarantee all medical terms and homoglyphs are 100% clean
    for seg in formatted_segments:
        seg.text = apply_dictionary(seg.text)

    # Always stitch boundary breaks, eliminate orphaned micro-segments, and guarantee 100% of segments have a role
    formatted_segments = assign_clinical_roles_rule_based(formatted_segments)

    # Re-apply dictionary on stitched segments to clean any combined terms
    for seg in formatted_segments:
        seg.text = apply_dictionary(seg.text)

    # Reconstruct final dialogue text with clear Doctor / Patient speaker labels
    final_text_lines = []
    for s in formatted_segments:
        if not s.text:
            continue
        label = s.role or s.speaker or "หมอ"
        final_text_lines.append(f"{label}: {s.text}")

    raw_dialogue = "\n\n".join(final_text_lines)
    full_final_text = raw_dialogue
    full_raw_text = "\n".join([s.text for s in formatted_segments if s.text])

    print(f"[POSTPROCESS COMPLETED] post_processed_by: {post_processed_by}, total segments: {len(formatted_segments)}")
    return formatted_segments, full_final_text, full_raw_text, post_processed_by


def post_process_transcript(text: str, mode: str | None = None) -> tuple[str, str]:
    settings = get_settings()
    selected_mode = normalize_post_process_mode(mode)

    if selected_mode == "none":
        return text, "none"

    dictionary_text = apply_dictionary(text)
    system_instruction = get_proofread_system_prompt()
    openai_success = False

    # 1. Try OpenAI if configured
    if selected_mode in {"openai"} and settings.openai_api_key:
        try:
            client = OpenAI(api_key=settings.openai_api_key)
            target_model = settings.openai_model or "gpt-4o-mini"
            if "gpt-5" in target_model:
                target_model = "gpt-4o-mini"

            try:
                chat_resp = client.chat.completions.create(
                    model=target_model,
                    messages=[
                        {"role": "system", "content": system_instruction},
                        {"role": "user", "content": f"Correct this medical transcript and diarize speakers into [แพทย์] and [คนไข้]:\n\n{dictionary_text}"},
                    ],
                    temperature=0.0,
                )
                corrected = chat_resp.choices[0].message.content.strip()
                if corrected:
                    return corrected, f"openai:{target_model}"
            except Exception as e:
                print(f"OpenAI chat completion fallback attempt: {e}")
                chat_resp = client.chat.completions.create(
                    model="gpt-4o-mini",
                    messages=[
                        {"role": "system", "content": system_instruction},
                        {"role": "user", "content": f"Correct this medical transcript and diarize speakers into [แพทย์] and [คนไข้]:\n\n{dictionary_text}"},
                    ],
                    temperature=0.0,
                )
                corrected = chat_resp.choices[0].message.content.strip()
                if corrected:
                    return corrected, "openai:gpt-4o-mini"

        except Exception as err:
            print(f"OpenAI postprocess error: {err}")

    # 2. Try Gemini if configured or as fallback
    if (not openai_success) and selected_mode in {"gemini", "openai"} and settings.gemini_api_key:
        try:
            gemini_res = call_gemini_proofread_text(dictionary_text, settings.gemini_api_key)
            if gemini_res:
                return gemini_res, "gemini:gemini-2.0-flash"
        except Exception as gemini_err:
            print(f"Gemini postprocess error: {gemini_err}")

    # 3. Rule-based clinical dialogue formatting fallback
    formatted_rule_based = format_clinical_dialogue_rule_based(dictionary_text)
    return formatted_rule_based, "dictionary"



