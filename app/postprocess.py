def clean_unicode_homoglyphs(text: str) -> str:
    """
    Clean up non-standard Unicode characters, Greek/Cyrillic homoglyphs,
    and BPE byte-fallback token artifacts in Thai Whisper outputs.
    """
    if not text:
        return ""
    cleaned = text
    for k, v in HOMOGLYPH_REPLACEMENTS.items():
        cleaned = cleaned.replace(k, v)
    return cleaned


def clean_stuttering_and_duplicates(text: str) -> str:
    """
    Clean up nested parentheses artifacts from recursive replacements,
    dragged repetitive vowels (e.g. คือออออ -> คือ, ทั้งคืออออน -> ทั้งคืน),
    and duplicated clauses.
    """
    if not text:
        return ""

    cleaned = text

    # Fix nested / duplicated Skin tags artifacts (e.g. Skin tags (Skin tags (สกินแท็ก))))
    cleaned = re.sub(r"(?:Skin\s*tags|\(สกินแท็ก\)|\(|\))+", lambda m: "Skin tags" if "Skin" in m.group(0) or "สกิน" in m.group(0) else "", cleaned)

    # Collapse dragged repetitive characters (3 or more consecutive identical characters -> 1)
    cleaned = re.sub(r"([ก-ฮะ-ูเ-์a-zA-Z])\1{2,}", r"\1", cleaned)

    # Clean specific elongated vowel / stutter hallucinations
    cleaned = re.sub(r"คือ[อ ]+", "คือ ", cleaned)
    cleaned = re.sub(r"ทั้งคือ+อ*น*", "ทั้งคืน", cleaned)
    cleaned = re.sub(r"ชีตั้งคืน*", "ฉี่ทั้งคืน", cleaned)
    cleaned = re.sub(r"ชีตั้ง", "ฉี่ทั้งคืน", cleaned)
    cleaned = re.sub(r"ชีตลอด", "ฉี่ตลอด", cleaned)
    cleaned = re.sub(r"หหลังคอ", "หลังคอ", cleaned)
    cleaned = re.sub(r"หหหลังคอ", "หลังคอ", cleaned)
    cleaned = re.sub(r"ค่ะบอกว่า", "เค้าบอกว่า", cleaned)
    cleaned = re.sub(r"Acanthocyt", "Acanthosis", cleaned)

    # Clean up any leftover duplicated words
    cleaned = re.sub(r"(Skin tags\s*)+", "Skin tags ", cleaned)
    cleaned = re.sub(r"(เราเรียกว่า\s*)+", "เราเรียกว่า ", cleaned)
    cleaned = re.sub(r"(หรือที่เราเรียกว่า\s*)+", "หรือที่เราเรียกว่า ", cleaned)
    cleaned = re.sub(r"(ติ่งผิวหนัง\s*)+", "ติ่งผิวหนัง ", cleaned)
    cleaned = re.sub(r"(ผิวหนัง\s*)+", "ผิวหนัง ", cleaned)
    cleaned = re.sub(r"(หลังคอ\s*)+", "หลังคอ ", cleaned)
    cleaned = re.sub(r"(รักแร้\s*)+", "รักแร้ ", cleaned)

    # Clean double spaces
    cleaned = re.sub(r"[ ]{2,}", " ", cleaned)
    return cleaned.strip()




def remove_duplicate_phrases(text: str) -> str:
    return clean_stuttering_and_duplicates(text)



